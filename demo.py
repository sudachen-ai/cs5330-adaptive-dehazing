"""Generate a deterministic synthetic smoke test, not a benchmark result."""
from pathlib import Path
import json
import cv2
import numpy as np
from dehaze import process, save_results, save_rgb


def scene():
    h, w = 240, 360
    image = np.empty((h, w, 3), np.float32)
    image[:] = (0.32, 0.56, 0.78)
    cv2.rectangle(image, (0, 115), (w, h), (0.18, 0.34, 0.16), -1)
    for x, y, width, height, color in [
        (22, 82, 66, 95, (0.48, 0.24, 0.15)),
        (125, 65, 74, 115, (0.62, 0.55, 0.34)),
        (240, 100, 85, 110, (0.22, 0.27, 0.35)),
    ]:
        cv2.rectangle(image, (x, y), (x + width, y + height), color, -1)
        for yy in range(y + 10, y + height - 8, 20):
            for xx in range(x + 8, x + width - 8, 19):
                cv2.rectangle(image, (xx, yy), (xx + 9, yy + 10), (0.03, 0.04, 0.05), -1)
    cv2.line(image, (80, 239), (180, 140), (0.65, 0.6, 0.5), 18)
    y, x = np.mgrid[0:h, 0:w].astype(np.float32)
    transmission = 0.28 + 0.55 * y / (h - 1)
    transmission -= 0.18 * np.exp(-((x - 270) ** 2 + (y - 120) ** 2) / 6500)
    transmission = np.clip(transmission, 0.15, 0.9)
    airlight = np.array([0.85, 0.88, 0.92], np.float32)
    hazy = image * transmission[..., None] + airlight * (1 - transmission[..., None])
    return image, hazy, transmission


if __name__ == "__main__":
    output = Path(__file__).parent / "examples" / "synthetic"
    clear, hazy, transmission = scene()
    results = process(hazy)
    save_results(results, output)
    save_rgb(output / "synthetic_clear.png", clear)
    save_rgb(output / "synthetic_true_transmission.png", transmission)
    (output / "provenance.json").write_text(json.dumps({
        "source": "Procedural illustration generated by demo.py; no external images.",
        "purpose": "Pipeline smoke test only. Not evidence of real-image improvement.",
        "seed": "Deterministic; no randomness.",
    }, indent=2) + "\n")
    print(f"Synthetic example saved to {output}")
